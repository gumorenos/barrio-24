import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

import { EXPECTED_STAGING } from './staging-constants.mjs'

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url))
export const DEFAULT_ENV_PATH = path.resolve(SCRIPT_DIR, '..', 'staging-config.env')
export const DEFAULT_OUTPUT_PATH = path.resolve(SCRIPT_DIR, '..', 'wrangler.toml')

export { EXPECTED_STAGING }

const REQUIRED_KEYS = Object.freeze([
  'BARRIO24_STAGING_ACCOUNT_ID',
  'BARRIO24_STAGING_WORKER_NAME',
  'BARRIO24_STAGING_D1_DATABASE_NAME',
  'BARRIO24_STAGING_D1_DATABASE_ID',
  'BARRIO24_STAGING_PAGES_ORIGIN',
  'BARRIO24_STAGING_CRON',
  'BARRIO24_STAGING_RATE_LIMIT_NAMESPACE_ID',
])

function unquote(value) {
  if (value.length < 2) return value
  const quote = value[0]
  if ((quote !== '"' && quote !== "'") || value.at(-1) !== quote) return value
  const inner = value.slice(1, -1)
  if (quote === "'") return inner
  return inner.replace(/\\([\\"nrt])/g, (_, token) => ({ '\\': '\\', '"': '"', n: '\n', r: '\r', t: '\t' })[token])
}

export function parseEnvFile(contents) {
  const values = {}
  for (const [index, rawLine] of contents.split(/\r?\n/).entries()) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const match = line.match(/^(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=\s*(.*)$/)
    if (!match) throw new Error(`Invalid staging env syntax on line ${index + 1}`)
    values[match[1]] = unquote(match[2].trim())
  }
  return values
}

export function mergeEnvironment(fileValues, processValues = process.env) {
  const merged = { ...fileValues }
  for (const key of REQUIRED_KEYS) if (typeof processValues[key] === 'string') merged[key] = processValues[key]
  return merged
}

function requireValue(env, key) {
  const value = env[key]?.trim()
  if (!value) throw new Error(`Missing required staging variable: ${key}`)
  return value
}

function expectExact(key, actual, expected) {
  if (actual !== expected) throw new Error(`${key} does not match the authorized staging value`)
}

export function validateStagingEnvironment(env) {
  const config = {
    accountId: requireValue(env, 'BARRIO24_STAGING_ACCOUNT_ID'),
    workerName: requireValue(env, 'BARRIO24_STAGING_WORKER_NAME'),
    d1DatabaseName: requireValue(env, 'BARRIO24_STAGING_D1_DATABASE_NAME'),
    d1DatabaseId: requireValue(env, 'BARRIO24_STAGING_D1_DATABASE_ID'),
    pagesOrigin: requireValue(env, 'BARRIO24_STAGING_PAGES_ORIGIN'),
    cron: requireValue(env, 'BARRIO24_STAGING_CRON'),
    rateLimitNamespaceId: requireValue(env, 'BARRIO24_STAGING_RATE_LIMIT_NAMESPACE_ID'),
  }
  expectExact('BARRIO24_STAGING_ACCOUNT_ID', config.accountId, EXPECTED_STAGING.accountId)
  expectExact('BARRIO24_STAGING_WORKER_NAME', config.workerName, EXPECTED_STAGING.workerName)
  expectExact('BARRIO24_STAGING_D1_DATABASE_NAME', config.d1DatabaseName, EXPECTED_STAGING.d1DatabaseName)
  expectExact('BARRIO24_STAGING_D1_DATABASE_ID', config.d1DatabaseId, EXPECTED_STAGING.d1DatabaseId)
  expectExact('BARRIO24_STAGING_PAGES_ORIGIN', config.pagesOrigin, EXPECTED_STAGING.pagesOrigin)
  expectExact('BARRIO24_STAGING_CRON', config.cron, EXPECTED_STAGING.cron)
  let origin
  try { origin = new URL(config.pagesOrigin) } catch { throw new Error('BARRIO24_STAGING_PAGES_ORIGIN must be a valid URL') }
  if (origin.protocol !== 'https:' || origin.origin !== config.pagesOrigin) throw new Error('BARRIO24_STAGING_PAGES_ORIGIN must be an HTTPS origin without path, query, or fragment')
  if (!/^[1-9]\d*$/.test(config.rateLimitNamespaceId)) throw new Error('BARRIO24_STAGING_RATE_LIMIT_NAMESPACE_ID must be a positive integer string')
  return Object.freeze(config)
}

export function renderWranglerToml(config) {
  return `# Generated by api/scripts/render-staging-wrangler-config.mjs.\n# Do not edit or commit api/wrangler.toml.\nname = "${config.workerName}"\nmain = "src/index.ts"\ncompatibility_date = "${EXPECTED_STAGING.compatibilityDate}"\naccount_id = "${config.accountId}"\n\n[vars]\nALLOWED_ORIGIN = "${config.pagesOrigin}"\n\n[[d1_databases]]\nbinding = "DB"\ndatabase_name = "${config.d1DatabaseName}"\ndatabase_id = "${config.d1DatabaseId}"\n\n[[ratelimits]]\nname = "REPORTS_RATE_LIMITER"\nnamespace_id = "${config.rateLimitNamespaceId}"\n\n  [ratelimits.simple]\n  limit = 10\n  period = 60\n\n[triggers]\ncrons = ["${config.cron}"]\n`
}

async function loadOptionalEnvFile(envPath) {
  if (!existsSync(envPath)) return {}
  return parseEnvFile(await readFile(envPath, 'utf8'))
}

export async function generateStagingConfig({ envPath = DEFAULT_ENV_PATH, outputPath = DEFAULT_OUTPUT_PATH, processValues = process.env } = {}) {
  await rm(outputPath, { force: true })
  const fileValues = await loadOptionalEnvFile(envPath)
  const config = validateStagingEnvironment(mergeEnvironment(fileValues, processValues))
  const contents = renderWranglerToml(config)
  const temporaryPath = `${outputPath}.${process.pid}.tmp`
  await writeFile(temporaryPath, contents, { encoding: 'utf8', mode: 0o600 })
  await rename(temporaryPath, outputPath)
  return { outputPath, contents, config }
}

async function main() {
  try {
    const { outputPath } = await generateStagingConfig()
    console.log(`[staging:config] generated ${path.relative(process.cwd(), outputPath)}`)
  } catch (error) {
    await rm(DEFAULT_OUTPUT_PATH, { force: true })
    console.error(`[staging:config] ${error instanceof Error ? error.message : String(error)}`)
    process.exitCode = 1
  }
}

const invokedAsScript = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedAsScript) await main()
